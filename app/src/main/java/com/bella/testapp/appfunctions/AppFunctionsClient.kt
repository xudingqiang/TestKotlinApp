package com.bella.testapp.appfunctions

import android.content.Context
import android.os.Build
import androidx.appfunctions.AppFunctionData
import androidx.appfunctions.AppFunctionManager
import androidx.appfunctions.AppFunctionSerializable
import androidx.appfunctions.ExecuteAppFunctionRequest
import androidx.appfunctions.ExecuteAppFunctionResponse

/**
 * Argument object passed to the demo AppFunction published by the target app
 * (`com.bella.funcprovider`).
 *
 * `@AppFunctionSerializable` makes the appfunctions-compiler KSP processor generate a
 * `$AddParametersFactory`, which is what [AppFunctionData.serialize] looks up when it converts this
 * instance into the wire format (`GenericDocument`) that
 * `android.app.appfunctions.AppFunctionManager.executeAppFunction` expects.
 */
@AppFunctionSerializable
data class AddParameters(
    val a: Int,
    val b: Int,
)

/** Result of executing a function through AppFunctions. */
sealed interface AgentFunctionResult {
    data class Success(val displayText: String, val raw: String) : AgentFunctionResult
    data class Failure(val displayText: String, val cause: Throwable? = null) : AgentFunctionResult
}

/**
 * Thin wrapper around `android.app.appfunctions.AppFunctionManager` for the demo.
 *
 * AppFunctions are the platform mechanism that lets an app publish capabilities
 * (`@AppFunction`) that another app — typically the on-device AI agent — may discover and invoke.
 * This class is the "agent" side: it builds an [ExecuteAppFunctionRequest] for a function owned by
 * another package and runs it.
 */
class AppFunctionsClient(private val context: Context) {

    companion object {
        /** Package of the target app in this repository (`:funcprovider`). */
        const val PROVIDER_PACKAGE = "com.bella.funcprovider"

        /**
         * Function id generated by the appfunctions-compiler for
         * `com.bella.funcprovider.BaseDemoAppFunctionService#add`.
         */
        const val FUNC_ADD =
            "com.bella.funcprovider.BaseDemoAppFunctionService#add"

        /** Minimum SDK level that exposes `android.app.appfunctions`. */
        const val MIN_SDK_FOR_APP_FUNCTIONS = Build.VERSION_CODES.BAKLAVA
    }

    /** True when this device can run the cross-app AppFunctions path at all. */
    val isSupported: Boolean =
        Build.VERSION.SDK_INT >= MIN_SDK_FOR_APP_FUNCTIONS &&
            AppFunctionManager.getInstance(context) != null

    /**
     * Executes [FUNC_ADD] in [PROVIDER_PACKAGE] and returns the integer the remote function
     * produced.
     */
    suspend fun callAdd(a: Int, b: Int): AgentFunctionResult {
        if (Build.VERSION.SDK_INT < MIN_SDK_FOR_APP_FUNCTIONS) {
            return AgentFunctionResult.Failure(
                "当前设备是 API ${Build.VERSION.SDK_INT}，" +
                    "AppFunctions(android.app.appfunctions) 需要 API $MIN_SDK_FOR_APP_FUNCTIONS。",
            )
        }

        val manager = AppFunctionManager.getInstance(context)
            ?: return AgentFunctionResult.Failure(
                "AppFunctionManager 不可用（设备未实现 AppFunctions 扩展）。",
            )

        return try {
            val parameters = AppFunctionData.serialize(
                AddParameters(a = a, b = b),
                AddParameters::class.java,
            )
            val request = ExecuteAppFunctionRequest(
                targetPackageName = PROVIDER_PACKAGE,
                functionIdentifier = FUNC_ADD,
                functionParameters = parameters,
            )
            val response = manager.executeAppFunction(request)
            when (response) {
                is ExecuteAppFunctionResponse.Success -> {
                    val value = response.returnValue.getInt(
                        ExecuteAppFunctionResponse.Success.PROPERTY_RETURN_VALUE,
                    )
                    AgentFunctionResult.Success(
                        displayText = "$a + $b = $value",
                        raw = value.toString(),
                    )
                }

                is ExecuteAppFunctionResponse.Error -> AgentFunctionResult.Failure(
                    displayText = "AppFunctions 返回错误：${response.error}",
                    cause = response.error,
                )
            }
        } catch (t: Throwable) {
            AgentFunctionResult.Failure(
                displayText = "AppFunctions 调用失败：${t.javaClass.simpleName}: ${t.message}",
                cause = t,
            )
        }
    }
}
